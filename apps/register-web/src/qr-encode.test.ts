describe("encodeQr", () => {
  for (const vector of VECTORS) {
    it(`バージョン${vector.version}の行列が期待と一致する: ${vector.text.slice(0, 24)}`, () => {
      const result = encodeQr(vector.text);
      expect(result.version).toBe(vector.version);
      expect(result.size).toBe(vector.rows.length);
      expect(result.modules.map((row) => row.map((v) => (v ? "1" : "0")).join(""))).toEqual(vector.rows);
    });
  }

  it("容量を超える文字列は例外にする", () => {
    expect(() => encodeQr("A".repeat(214))).toThrow("QRコードに収まらない長さです");
  });

  it("空文字列でもバージョン1で生成できる", () => {
    const result = encodeQr("");
    expect(result.version).toBe(1);
    expect(result.size).toBe(21);
  });
});
